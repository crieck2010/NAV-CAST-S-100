/**
 * Native MapLibre GL MapView Composable integrated with Jetpack Compose lifecycle.
 * Displays base map in #0B132B dark maritime styling with interactive S-100 overlays.
 */
@Composable
fun MapLibreMapView(
  surveyArea: SurveyArea,
  selectedSounding: S102Sounding?,
  selectedBuoy: MaritimeBuoy?,
  selectedHazard: NauticalHazard?,
  selectedAis: AisTarget?,
  ukcStatus: UkcStatus,
  vesselSpeedKnots: Float,
  layerBathymetry: Boolean,
  layerCurrents: Boolean,
  layerAtoNBuoys: Boolean,
  layerHazards: Boolean,
  layerDredgedChannel: Boolean,
  layerAnchorages: Boolean,
  layerAisTraffic: Boolean,
  layerSoundings: Boolean,
  is3dPerspective: Boolean,
  onSoundingTapped: (S102Sounding?) -> Unit,
  onBuoyTapped: (MaritimeBuoy?) -> Unit,
  onHazardTapped: (NauticalHazard?) -> Unit,
  onAisTapped: (AisTarget?) -> Unit,
  modifier: Modifier = Modifier
) {
  val context = LocalContext.current
  val lifecycleOwner = LocalLifecycleOwner.current

  // Initialize MapLibre GL Native once per application context
  remember {
    MapLibre.getInstance(context)
  }

  var mapLibreMapInstance by remember { mutableStateOf<MapLibreMap?>(null) }
  val mapView = remember {
    MapView(context).apply {
      getMapAsync { map ->
        mapLibreMapInstance = map
        map.uiSettings.isAttributionEnabled = false
        map.uiSettings.isLogoEnabled = false
        map.uiSettings.isCompassEnabled = false

        // Load custom dark slate maritime style matching #0B132B
        map.setStyle(Style.Builder().fromJson(MapLibreStyleHelper.getDarkMaritimeStyleJson())) {
          // Camera setup for survey area
          val target = LatLng(surveyArea.centerLat, surveyArea.centerLon)
          val position = CameraPosition.Builder()
            .target(target)
            .zoom(12.5)
            .tilt(if (is3dPerspective) 48.0 else 0.0)
            .build()
          map.animateCamera(CameraUpdateFactory.newCameraPosition(position), 800)
        }
      }
    }
  }

  // Manage Android Lifecycle for MapView
  DisposableEffect(lifecycleOwner, mapView) {
    val observer = LifecycleEventObserver { _, event ->
      when (event) {
        Lifecycle.Event.ON_START -> mapView.onStart()
        Lifecycle.Event.ON_RESUME -> mapView.onResume()
        Lifecycle.Event.ON_PAUSE -> mapView.onPause()
        Lifecycle.Event.ON_STOP -> mapView.onStop()
        Lifecycle.Event.ON_DESTROY -> mapView.onDestroy()
        else -> {}
      }
    }
    lifecycleOwner.lifecycle.addObserver(observer)
    onDispose {
      lifecycleOwner.lifecycle.removeObserver(observer)
      mapView.onDestroy()
    }
  }

  // Animate camera when survey area or 3D tilt perspective changes
  LaunchedEffect(surveyArea, is3dPerspective) {
    mapLibreMapInstance?.let { map ->
      val target = LatLng(surveyArea.centerLat, surveyArea.centerLon)
      val cameraPosition = CameraPosition.Builder()
        .target(target)
        .zoom(12.5)
        .tilt(if (is3dPerspective) 48.0 else 0.0)
        .build()
      map.animateCamera(CameraUpdateFactory.newCameraPosition(cameraPosition), 1000)
    }
  }

  Box(
    modifier = modifier
      .fillMaxSize()
      .background(NavyBackground)
      .testTag("maplibre_map_view_root")
  ) {
    // 1. MapLibre GL Native MapView
    AndroidView(
      factory = { mapView },
      modifier = Modifier.fillMaxSize().testTag("native_maplibre_view")
    )

    // 2. High-Precision S-100 Bathymetric, Hydrodynamic Current & Symbology Layer Overlay
    MapLibreNauticalMap(
      surveyArea = surveyArea,
      selectedSounding = selectedSounding,
      selectedBuoy = selectedBuoy,
      selectedHazard = selectedHazard,
      selectedAis = selectedAis,
      ukcStatus = ukcStatus,
      vesselSpeedKnots = vesselSpeedKnots,
      layerBathymetry = layerBathymetry,
      layerCurrents = layerCurrents,
      layerAtoNBuoys = layerAtoNBuoys,
      layerHazards = layerHazards,
      layerDredgedChannel = layerDredgedChannel,
      layerAnchorages = layerAnchorages,
      layerAisTraffic = layerAisTraffic,
      layerSoundings = layerSoundings,
      is3dPerspective = is3dPerspective,
      onSoundingTapped = onSoundingTapped,
      onBuoyTapped = onBuoyTapped,
      onHazardTapped = onHazardTapped,
      onAisTapped = onAisTapped,
      modifier = Modifier.fillMaxSize()
    )

    // 3. MapLibre Engine Status Watermark Pill (Top Right)
    Row(
      modifier = Modifier
        .align(Alignment.TopEnd)
        .padding(top = 52.dp, end = 12.dp)
        .clip(RoundedCornerShape(6.dp))
        .background(NavySurface.copy(alpha = 0.85f))
        .border(1.dp, NavySurfaceHighlight, RoundedCornerShape(6.dp))
        .padding(horizontal = 8.dp, vertical = 3.dp),
      verticalAlignment = Alignment.CenterVertically
    ) {
      Box(modifier = Modifier.size(6.dp).clip(CircleShape).background(EmeraldSafe))
      Spacer(modifier = Modifier.width(5.dp))
      Text(
        text = "MAPLIBRE GL NATIVE #0B132B",
        color = NeonCyan,
        fontSize = 8.sp,
        fontWeight = FontWeight.Bold,
        fontFamily = FontFamily.Monospace
      )
    }
  }
}
